#!/usr/bin/env bash
# Regenerate NOTICE: licences of the Rust crates and npm packages that ship
# (server + shared for Linux, the web app's production packages).
#
#   tools/notice.sh                      # needs cargo-about and web/node_modules (npm ci)
#   NODE_MODULES=/path/node_modules tools/notice.sh
set -euo pipefail
cd "$(dirname "$0")/.."
NM="${NODE_MODULES:-web/node_modules}"
[ -d "$NM" ] || { echo "no $NM: run npm ci in web/ (or set NODE_MODULES)"; exit 1; }
rust="$(mktemp)"; log="$(mktemp)"; trap 'rm -f "$rust" "$log"' EXIT
cargo about generate -m crates/server/Cargo.toml --locked \
  --target x86_64-unknown-linux-gnu about.hbs > "$rust" 2> "$log" \
  || { cat "$log"; exit 1; }

python3 - "$rust" "$NM" web/package-lock.json > NOTICE <<'PY'
import json, pathlib, re, sys

rust, nm, lock = sys.argv[1], pathlib.Path(sys.argv[2]), sys.argv[3]
out = []
out.append("""Glut & Flut (Elements)
Copyright (C) 2026 Thorsten Riess, Scientific Wave Solutions
Licensed under the GNU Affero General Public License v3.0 or later (LICENSE).

This file lists the third-party software that ships with the server and the
web app, with their licences. It is generated by tools/notice.sh; do not edit.

Fetched at build or deploy time, not part of this repository:
- Basemap tiles: Protomaps (https://protomaps.com), built from OpenStreetMap
  data, (c) OpenStreetMap contributors, Open Database License (ODbL) 1.0.
- Map fonts: Noto Sans (Regular, Medium, Italic), SIL Open Font License 1.1,
  shipped with OFL.txt; fonts and sprites come from the protomaps/basemaps-assets
  repository (see its licence files).

""")

# npm: production packages of the web app (dev tools left out).
pkgs = json.load(open(lock))["packages"]
rows, texts = [], {}
for path, meta in sorted(pkgs.items()):
    if not path or meta.get("dev"):
        continue
    d = nm / path.removeprefix("node_modules/")
    pj = json.load(open(d / "package.json"))
    lic = pj.get("license") or meta.get("license") or "see package"
    if isinstance(lic, dict):
        lic = lic.get("type", "see package")
    name = path.removeprefix("node_modules/")
    rows.append(f"{name} {meta.get('version')}: {lic}")
    found = False
    for f in sorted(d.iterdir()):
        if re.match(r"(?i)(licen[cs]e|copying|notice)", f.name) and f.is_file():
            texts.setdefault(f.read_text(errors="replace").strip(), []).append(name)
            found = True
    if not found:
        # No licence file in the package: name the holder and the standard text.
        author = pj.get("author") or "its authors"
        if isinstance(author, dict):
            author = author.get("name", "its authors")
        texts.setdefault(f"Copyright (c) {author}. Licensed under {lic} "
                         f"(no licence file in the package; text: https://spdx.org/licenses/{lic}.html).",
                         []).append(name)
out.append("npm packages (web app, production)\n----------------------------------\n")
out += rows
out.append("\nLicence texts of the npm packages\n---------------------------------")
for text, users in texts.items():
    out.append(f"\n=== used by: {' '.join(users)}\n\n{text}")

# Rust, without our own crates and their AGPL text (that is LICENSE).
r = open(rust).read()
r = "\n".join(l for l in r.split("\n") if not l.startswith("elements-"))
r = re.sub(r"\n=== [^\n]*\(AGPL-3\.0-or-later\).*?(?=\n=== |\Z)", "", r, flags=re.S)
out.append("\n\n" + r.strip())
print("\n".join(out).rstrip() + "")
PY
echo "NOTICE: $(wc -c < NOTICE) bytes"
